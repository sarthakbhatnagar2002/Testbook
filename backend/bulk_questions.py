def get_or_create_subject(db, name: str, creator_id: str) -> models.Subject:
    subject = db.execute(select(models.Subject).where(models.Subject.name == name)).scalar_one_or_none()
    if subject:
        return subject
    subject = models.Subject(name=name, created_by=creator_id)
    db.add(subject)
    db.commit()
    db.refresh(subject)
    return subject


def add_questions(db, subject: models.Subject, creator_id: str, items: list[tuple]) -> int:
    existing_texts = {
        q.text for q in db.execute(select(models.Question).where(models.Question.subject_id == subject.id)).scalars()
    }
    added = 0
    for text, options, correct_index, explanation in items:
        if text in existing_texts:
            continue
        question = models.Question(
            subject_id=subject.id, created_by=creator_id, text=text, explanation=explanation
        )
        question.options = [
            models.Option(text=opt, position=i, is_correct=(i == correct_index))
            for i, opt in enumerate(options)
        ]
        db.add(question)
        added += 1
    db.commit()
    return added


def main() -> None:
    db = SessionLocal()
    try:
        creator = db.execute(select(models.User)).scalars().first()
        if not creator:
            creator = models.User(
                name="Demo User", email="demo@example.com", password_hash=hash_password("password123")
            )
            db.add(creator)
            db.commit()
            db.refresh(creator)
            print("No existing user found -- created demo@example.com (password: password123).")

        subjects_and_items = [
            ("Physics", PHYSICS),
            ("Chemistry", CHEMISTRY),
            ("Mathematics", MATHEMATICS),
            ("Biology", BIOLOGY),
            ("Computer Science", COMPUTER_SCIENCE),
            ("English", ENGLISH),
        ]
        for name, items in subjects_and_items:
            subject = get_or_create_subject(db, name, creator.id)
            added = add_questions(db, subject, creator.id, items)
            total = len(
                db.execute(select(models.Question).where(models.Question.subject_id == subject.id)).scalars().all()
            )
            print(f"{name}: added {added} new questions ({total} total in this subject now).")
    finally:
        db.close()


